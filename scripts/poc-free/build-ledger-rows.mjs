#!/usr/bin/env node
// build-ledger-rows.mjs - generate the schema_migrations ledger rows for the
// migrations that were applied without their journal row.
//
// WHY THIS IS GENERATED AND NOT HAND-WRITTEN. The `statements` column holds the
// migration's own text. Pasting three files into a SQL document by hand is how a
// ledger row ends up describing something other than what ran, and a ledger that
// disagrees with the schema is the exact defect this whole exercise is fixing.
// The generator reads the migration files, so the row cannot drift from them.
//
// It NEVER connects to a database, reads no credential, and writes one file.
//
// Usage:  node scripts/poc-free/build-ledger-rows.mjs [out.sql]
//         default out: scripts/ledger-rows-0010-0012.sql
//         --check      regenerate into memory, diff against the committed file,
//                      and PARSE the committed file with the real PostgreSQL
//                      grammar. Exit 1 on any difference or any forbidden
//                      statement. Exit 0 when the file is what it claims to be.
//
// THE PARSE IS THE POINT, not decoration. CLAUDE.md 8.6 requires a file to be
// parsed with pgsql-parser before it goes near the database. This one embeds
// three migrations as string literals, and those migrations contain the words
// DROP, DELETE and ALTER inside their own text. The grammar is the only thing
// that can tell the difference between a DELETE that runs and the seven letters
// D-E-L-E-T-E sitting inside a quoted string, and reading it by eye is exactly
// how somebody talks themselves into the wrong answer.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');

// version -> the migration file, and the `name` the ledger row carries. The
// name is the file's basename with the four-digit prefix and the extension
// stripped, which is the Supabase CLI's own convention.
const ROWS = [
  { version: '0010', file: 'supabase/migrations/0010_confirm_extraction_draft.sql' },
  { version: '0011', file: 'supabase/migrations/0011_extraction_confirm_corrections.sql' },
  { version: '0012', file: 'supabase/migrations/0012_manager_flagged_products.sql' },
];

// The dollar-quote tag. Every migration here contains single quotes and its own
// $$-quoted function bodies, so a plain string literal would need escaping that
// nobody can read and $$ would collide. $mig$ is asserted absent below rather
// than assumed absent: a collision would silently truncate the row's text.
const TAG = '$mig$';

const parts = [];
parts.push(`-- scripts/ledger-rows-0010-0012.sql
-- GENERATED by scripts/poc-free/build-ledger-rows.mjs. Do not hand-edit.
-- Regenerate with:  node scripts/poc-free/build-ledger-rows.mjs
-- Verify with:      node scripts/poc-free/build-ledger-rows.mjs --check
--
-- Card P2-19. The three schema_migrations rows that were never written.
--
-- THIS FILE CHANGES NO SCHEMA. It writes three rows into Supabase's own
-- bookkeeping table, supabase_migrations.schema_migrations, whose newest row is
-- 0009 while the database itself is at 0012. Every column, constraint, function,
-- policy and grant described by 0010, 0011 and 0012 is already in place and
-- journalled in docs/migrations/APPLY-LOG.md. What is missing is the record.
--
-- WHY IT MATTERS: anything that reads that ledger to decide what is pending
-- (supabase db push, a future CLI-driven apply, or a human asking "what is
-- applied?") concludes that 0010, 0011 and 0012 are still to come, and tries to
-- run them again.
--
-- IT CONTAINS NO DROP, NO TRUNCATE AND NO DELETE. Three INSERTs, each
-- ON CONFLICT DO NOTHING, so running it twice is not an error and running it
-- after someone else has already done it is not an error either.
--
-- IT IS WRAPPED SO IT CAN BE INSPECTED BEFORE IT COMMITS. The transaction is
-- opened here and NOT closed. Read the RETURNING output, then send COMMIT; or
-- ROLLBACK; yourself. A file that commits on your behalf is a file you cannot
-- change your mind about.

begin;

-- Phase 1, pre-check. What the ledger holds BEFORE anything is written.
-- Expect the newest version to be 0010 or lower. If 0010, 0011 and 0012 are
-- already listed, someone has run this: send ROLLBACK; and stop.
select version, name from supabase_migrations.schema_migrations order by version;
select count(*) as ledger_rows_before from supabase_migrations.schema_migrations;
`);

for (const row of ROWS) {
  const path = resolve(REPO, row.file);
  const text = readFileSync(path, 'utf8');
  if (text.includes(TAG)) {
    console.error(`refusing to generate: ${row.file} contains the dollar-quote tag ${TAG}, which would truncate the row.`);
    process.exit(1);
  }
  const base = row.file.split('/').pop().replace(/\.sql$/, '');
  const name = base.replace(/^\d{4}_/, '');
  parts.push(`
-- Phase 2, apply. ${row.version}, ${name}, ${text.length} characters of SQL.
insert into supabase_migrations.schema_migrations (version, name, statements)
values ('${row.version}', '${name}', array[${TAG}${text}${TAG}])
on conflict (version) do nothing
returning version, name;
`);
}

parts.push(`
-- Phase 3, post-check. What the ledger holds AFTER the three inserts, still
-- inside the open transaction. Expect twelve rows, 0001 through 0012.
select version, name from supabase_migrations.schema_migrations order by version;
select count(*) as ledger_rows_after from supabase_migrations.schema_migrations;

-- Nothing is committed yet. Send COMMIT; to keep it, or ROLLBACK; to discard it.
`);

const sql = parts.join('');
const outPath = resolve(REPO, process.argv[2] && process.argv[2] !== '--check' ? process.argv[2] : 'scripts/ledger-rows-0010-0012.sql');

if (process.argv.includes('--check')) {
  let committed;
  try {
    committed = readFileSync(outPath, 'utf8');
  } catch {
    console.error(`FAIL  ${outPath} is missing. Run: node scripts/poc-free/build-ledger-rows.mjs`);
    process.exit(1);
  }
  if (committed !== sql) {
    console.error(`FAIL  ${outPath} does not match the migration files it is generated from. Regenerate it.`);
    process.exit(1);
  }
  console.log(`CHECK 1 generated: OK, ${outPath} matches the three migration files it is generated from.`);

  const { loadModule, parseSync } = await import('pgsql-parser');
  let parsed;
  try {
    await loadModule();
    parsed = parseSync(committed);
  } catch (error) {
    console.error('CHECK 2 parse: FAIL');
    console.error(String(error instanceof Error ? (error.stack ?? error.message) : error));
    process.exit(1);
  }

  const statements = Array.isArray(parsed?.stmts) ? parsed.stmts : [];
  const kinds = statements.map((s) => Object.keys(s.stmt ?? {})[0] ?? '<empty>');
  console.log(`CHECK 2 parse: OK, ${statements.length} statements, PostgreSQL grammar ${parsed.version}`);

  // The whole allowed vocabulary of this file. One transaction opener, the
  // pre-check and post-check selects, and the three inserts. Nothing else has
  // any business being here.
  const ALLOWED_KINDS = new Set(['TransactionStmt', 'SelectStmt', 'InsertStmt']);
  const EXPECTED_INSERTS = ROWS.length;

  const failures = [];
  const unexpected = kinds.filter((k) => !ALLOWED_KINDS.has(k));
  if (unexpected.length === 0) {
    console.log(`CHECK 3 statement kinds: OK, only ${[...new Set(kinds)].join(', ')}`);
  } else {
    failures.push(`CHECK 3 statement kinds: outside the allowed set: ${[...new Set(unexpected)].join(', ')}`);
  }

  const inserts = kinds.filter((k) => k === 'InsertStmt').length;
  if (inserts === EXPECTED_INSERTS) {
    console.log(`CHECK 4 insert count: OK, ${inserts}`);
  } else {
    failures.push(`CHECK 4 insert count: expected ${EXPECTED_INSERTS}, found ${inserts}`);
  }

  // The three targets, and only those three. An insert into any other table
  // would be a schema change wearing a bookkeeping file's name.
  const targets = statements
    .map((s) => s.stmt?.InsertStmt?.relation)
    .filter(Boolean)
    .map((r) => `${r.schemaname ?? 'public'}.${r.relname}`);
  const wrongTarget = targets.filter((t) => t !== 'supabase_migrations.schema_migrations');
  if (wrongTarget.length === 0) {
    console.log(`CHECK 5 insert targets: OK, all ${targets.length} into supabase_migrations.schema_migrations`);
  } else {
    failures.push(`CHECK 5 insert targets: unexpected targets ${[...new Set(wrongTarget)].join(', ')}`);
  }

  // The transaction is opened and deliberately never closed, so the owner reads
  // the post-check before deciding. A COMMIT reaching this file would take that
  // decision away from him.
  const txKinds = statements
    .map((s) => s.stmt?.TransactionStmt?.kind)
    .filter((k) => k !== undefined);
  const closers = txKinds.filter((k) => k !== 'TRANS_STMT_BEGIN' && k !== 'TRANS_STMT_START');
  if (txKinds.length === 1 && closers.length === 0) {
    console.log('CHECK 6 transaction: OK, one BEGIN and no COMMIT, so the owner decides');
  } else {
    failures.push(`CHECK 6 transaction: expected exactly one opener and no closer, found ${JSON.stringify(txKinds)}`);
  }

  if (failures.length > 0) {
    for (const f of failures) console.error(f);
    process.exit(1);
  }
  console.log(`PASS  ${outPath}`);
  process.exit(0);
}

writeFileSync(outPath, sql);
console.log(`wrote ${outPath}  (${sql.length} characters, ${ROWS.length} ledger rows)`);
